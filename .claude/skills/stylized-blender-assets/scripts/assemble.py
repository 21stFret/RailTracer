"""
Combine kit_lib.py (+ optional project helper libs) + a piece script into ONE paste-ready Blender script.

    python assemble.py piece.py -o /mnt/user-data/outputs/<kit>.py [--with ../assets/projects/fathom/fathom_lib.py]

Layout of the result:  piece docstring -> CONFIG block (hoisted from the piece) -> kit_lib -> project libs -> piece.
The CONFIG block is the part of the piece between '# >>> CONFIG' and '# <<< CONFIG' (EXPORT_DIR, KIT_NAME,
seeds, toggles): hoisting it puts everything the user may want to edit at the very top of the file.
The piece must NOT import the lib; it just uses its names (MB, Asset, wall, run, ...).
"""
import argparse, glob, os
here = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("piece")
ap.add_argument("-o", "--out", required=True)
ap.add_argument("--with", dest="libs", action="append", default=[], help="project helper lib(s), in order")
ap.add_argument("--unity-tool", dest="tools", action="append", default=[],
                help="extra Unity editor script(s) to embed (the core tools in assets/unity are always embedded)")
ap.add_argument("--no-unity-tools", action="store_true")
a = ap.parse_args()
lib = open(os.path.join(here, "kit_lib.py")).read()
piece = open(a.piece).read()
doc = ""
if piece.lstrip().startswith('"""'):
    s = piece.index('"""'); e = piece.index('"""', s + 3) + 3
    doc, piece = piece[s:e] + "\n", piece[e:]
config = ""
if "# >>> CONFIG" in piece and "# <<< CONFIG" in piece:
    s = piece.index("# >>> CONFIG"); e = piece.index("# <<< CONFIG") + len("# <<< CONFIG")
    config, piece = piece[s:e] + "\n", piece[:s] + piece[e:]
with open(a.out, "w") as f:
    f.write(doc)
    f.write("# Generated by stylized-blender-assets. Run in Blender (Scripting tab > Run Script) or:\n"
            "#   blender --python THIS_FILE.py                      (open Blender with the scene built)\n"
            "#   blender -b --python THIS_FILE.py -- --out <folder>   (headless export)\n\n")
    if config:
        f.write("# ======================================================================\n"
                "# CONFIG  -  edit these\n"
                "# ======================================================================\n" + config + "\n")
    if not a.no_unity_tools:
        core = sorted(glob.glob(os.path.join(here, "..", "assets", "unity", "*.cs")))
        tools = {os.path.splitext(os.path.basename(p))[0]: open(p, encoding="utf-8").read() for p in core + a.tools}
        f.write("# Unity editor tools, installed into the Unity project that contains the export folder.\n")
        f.write("UNITY_TOOLS = {\n" + "".join(f"    {k!r}: {v!r},\n" for k, v in tools.items()) + "}\n\n")
    f.write(lib)
    f.write("\n\n" + open(os.path.join(here, "kit_textures.py")).read())
    for p in a.libs:
        f.write(f"\n\n# ======================================================================\n"
                f"# PROJECT LIB: {os.path.basename(p)}\n"
                f"# ======================================================================\n")
        f.write(open(p).read())
    f.write("\n\n# ======================================================================\n# PIECE\n"
            "# ======================================================================\n")
    f.write(piece)
compile(open(a.out).read(), a.out, "exec")
print("wrote", a.out)
