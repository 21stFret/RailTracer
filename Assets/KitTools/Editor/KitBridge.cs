// Kit Bridge - build kits from inside Unity. Installed automatically by stylized-blender-assets kit scripts.
//
// Kit scripts live in Assets/KitScripts (the record of what built each asset folder).
//   Tools > Kit > Build Kit Script...  pick a kit .py -> confirm -> Blender runs it in the background,
//                                      then Unity refreshes; KitSetup makes the materials and the FBX
//                                      files import with colliders.
//   Tools > Kit > Rebuild Last Kit
//   Tools > Kit > Bridge Settings...   Blender path; optional: watch the Downloads folder (OFF by default)
//                                      so a downloaded kit script offers itself (Build / Ignore).
// When Claude Code builds a kit it writes the script into Assets/KitScripts and runs Blender itself;
// the bridge never auto-builds from that folder, so nothing is built twice.
// Nothing ever runs without your click.
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;
using Debug = UnityEngine.Debug;

[InitializeOnLoad]
public static class KitBridge
{
    const string Marker = "# Generated by stylized-blender-assets";
    const string PrefBlender = "KitBridge.BlenderPath";
    const string PrefWatch = "KitBridge.WatchDownloads";
    const string PrefLast = "KitBridge.LastScript";

    // path|timestamp already offered; SessionState survives script recompiles (no repeat dialogs)
    static bool Handled(string key) => SessionState.GetBool("KitBridge:" + key, false);
    static void MarkHandled(string key) => SessionState.SetBool("KitBridge:" + key, true);
    static readonly List<string> output = new List<string>();
    static Process running;
    static string runningKit, runningOut;
    static double nextPoll, startTime;

    static KitBridge() { EditorApplication.update += Update; }

    public static bool WatchDownloads
    {
        get => EditorPrefs.GetBool(PrefWatch, false);
        set => EditorPrefs.SetBool(PrefWatch, value);
    }

    public static string DownloadsDir =>
        Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), "Downloads");

    static string AssetsFull => Norm(Application.dataPath);
    static string ScriptsDir => AssetsFull + "/KitScripts";

    static string Norm(string p) => Path.GetFullPath(p).Replace('\\', '/').TrimEnd('/');

    // ------------------------------------------------------------------ polling
    static void Update()
    {
        if (running != null)
        {
            float t = (float)((EditorApplication.timeSinceStartup - startTime) / 60.0);
            if (EditorUtility.DisplayCancelableProgressBar("Kit Bridge",
                    $"Blender is building {runningKit}...", Mathf.Clamp01(t)))
            {
                try { running.Kill(); } catch { }
            }
            if (running.HasExited) Finish();
            return;
        }
        if (EditorApplication.timeSinceStartup < nextPoll) return;
        nextPoll = EditorApplication.timeSinceStartup + 2.0;
        if (EditorApplication.isCompiling || EditorApplication.isUpdating ||
            EditorApplication.isPlayingOrWillChangePlaymode) return;

        if (WatchDownloads) Scan(DownloadsDir);
    }

    static void Scan(string dir)
    {
        if (!Directory.Exists(dir)) return;
        string[] files;
        try { files = Directory.GetFiles(dir, "*.py"); } catch { return; }
        foreach (var f in files)
        {
            DateTime stamp;
            try { stamp = File.GetLastWriteTimeUtc(f); } catch { continue; }
            string key = Norm(f) + "|" + stamp.Ticks;
            if (Handled(key)) continue;
            if ((DateTime.UtcNow - stamp).TotalSeconds < 1.5) continue;          // still downloading
            MarkHandled(key);
            if (!IsKitScript(f)) continue;
            Offer(f);
            return;                                                             // one dialog at a time
        }
    }

    static bool IsKitScript(string path)
    {
        try
        {
            using (var r = new StreamReader(path))
            {
                for (int i = 0; i < 300 && !r.EndOfStream; i++)
                    if (r.ReadLine().StartsWith(Marker)) return true;
            }
        }
        catch { }
        return false;
    }

    // ------------------------------------------------------------------ offer + run
    public static void Offer(string script)
    {
        string text = File.ReadAllText(script);
        string kit = Grab(text, @"^KIT_NAME\s*=\s*r?[""']([^""']*)[""']") ?? Path.GetFileNameWithoutExtension(script);
        string exportDir = Grab(text, @"^EXPORT_DIR\s*=\s*r?[""']([^""']*)[""']") ?? "";
        string outDir = ResolveOut(exportDir, kit, out string note);
        string rel = "Assets" + outDir.Substring(AssetsFull.Length);

        int choice = EditorUtility.DisplayDialogComplex("Kit Bridge",
            $"Build kit \"{kit}\"?\n\nScript: {Path.GetFileName(script)}\nExport to: {rel}{note}\n\n" +
            "Blender runs the script in the background; the FBX files and materials then import here.",
            "Build", "Ignore", "Settings...");
        if (choice == 1) return;
        if (choice == 2) { KitBridgeSettings.Open(); return; }

        string archived = Archive(script);
        Run(archived, kit, outDir);
    }

    static string Grab(string text, string pattern)
    {
        var m = Regex.Match(text, pattern, RegexOptions.Multiline);
        return m.Success ? m.Groups[1].Value : null;
    }

    static string ResolveOut(string exportDir, string kit, out string note)
    {
        note = "";
        if (!string.IsNullOrWhiteSpace(exportDir))
        {
            try
            {
                string full = Norm(exportDir);
                if (full.StartsWith(AssetsFull + "/", StringComparison.OrdinalIgnoreCase) ||
                    string.Equals(full, AssetsFull, StringComparison.OrdinalIgnoreCase))
                    return AssetsFull + full.Substring(AssetsFull.Length);
                note = $"\n(The script's EXPORT_DIR is outside this project: {exportDir})";
            }
            catch { }
        }
        return AssetsFull + "/KitExports/" + kit;
    }

    static string Archive(string script)
    {
        Directory.CreateDirectory(ScriptsDir);
        string name = Regex.Replace(Path.GetFileName(script), @"\s*\(\d+\)(?=\.py$)", "");   // "kit (1).py" -> "kit.py"
        string dest = ScriptsDir + "/" + name;
        if (Norm(script) != dest)
        {
            File.Copy(script, dest, true);
            if (Norm(Path.GetDirectoryName(script)) != ScriptsDir)
                try { File.Delete(script); } catch { }
        }
        MarkHandled(dest + "|" + File.GetLastWriteTimeUtc(dest).Ticks);
        return dest;
    }

    public static void Run(string script, string kit, string outDir)
    {
        string blender = FindBlender();
        if (blender == null)
        {
            EditorUtility.DisplayDialog("Kit Bridge", "Blender was not found. Pick blender.exe (or the Blender app) next.", "OK");
            blender = EditorUtility.OpenFilePanel("Locate Blender", "", "");
            if (string.IsNullOrEmpty(blender)) return;
            EditorPrefs.SetString(PrefBlender, blender);
        }
        EditorPrefs.SetString(PrefLast, script);
        lock (output) output.Clear();
        var psi = new ProcessStartInfo(blender,
            $"-b --factory-startup --python \"{script}\" -- --out \"{outDir}\"")
        {
            UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true, CreateNoWindow = true
        };
        try
        {
            running = new Process { StartInfo = psi };
            running.OutputDataReceived += (s, e) => { if (e.Data != null) lock (output) output.Add(e.Data); };
            running.ErrorDataReceived += (s, e) => { if (e.Data != null) lock (output) output.Add(e.Data); };
            running.Start();
            running.BeginOutputReadLine();
            running.BeginErrorReadLine();
        }
        catch (Exception ex)
        {
            running = null;
            Debug.LogError($"[Kit Bridge] Could not start Blender ({blender}): {ex.Message}");
            return;
        }
        runningKit = kit; runningOut = outDir; startTime = EditorApplication.timeSinceStartup;
        Debug.Log($"[Kit Bridge] Building {kit} with {blender}");
    }

    static void Finish()
    {
        EditorUtility.ClearProgressBar();
        int code = -1;
        try { code = running.ExitCode; } catch { }
        running.Dispose(); running = null;
        string log;
        lock (output) log = string.Join("\n", output);
        bool failed = code != 0 || log.Contains("Traceback") || !log.Contains("Exported");
        string summary = output.LastOrDefault(l => l.StartsWith("Exported")) ?? "";
        if (failed)
            Debug.LogError($"[Kit Bridge] {runningKit} FAILED (exit {code}). Paste this log to Claude:\n{log}");
        else
            Debug.Log($"[Kit Bridge] {runningKit}: {summary}\n{log}");
        AssetDatabase.Refresh();          // FBX + palette import; KitSetup makes materials and re-imports
        string rel = "Assets" + runningOut.Substring(AssetsFull.Length);
        var folder = AssetDatabase.LoadAssetAtPath<UnityEngine.Object>(rel);
        if (folder != null) { EditorGUIUtility.PingObject(folder); }
    }

    // ------------------------------------------------------------------ blender discovery
    public static string FindBlender()
    {
        string pref = EditorPrefs.GetString(PrefBlender, "");
        if (!string.IsNullOrEmpty(pref) && File.Exists(pref)) return pref;
        var candidates = new List<string>();
        foreach (var pf in new[] { Environment.GetFolderPath(Environment.SpecialFolder.ProgramFiles),
                                   Environment.GetFolderPath(Environment.SpecialFolder.ProgramFilesX86) })
        {
            if (string.IsNullOrEmpty(pf)) continue;
            string foundation = Path.Combine(pf, "Blender Foundation");
            if (Directory.Exists(foundation))
                candidates.AddRange(Directory.GetDirectories(foundation)
                    .OrderByDescending(d => VersionOf(d))
                    .Select(d => Path.Combine(d, "blender.exe")));
            candidates.Add(Path.Combine(pf, "Steam", "steamapps", "common", "Blender", "blender.exe"));
        }
        candidates.Add("/Applications/Blender.app/Contents/MacOS/Blender");
        candidates.Add("/usr/bin/blender");
        candidates.Add("/snap/bin/blender");
        foreach (var dir in (Environment.GetEnvironmentVariable("PATH") ?? "").Split(Path.PathSeparator))
        {
            if (string.IsNullOrWhiteSpace(dir)) continue;
            candidates.Add(Path.Combine(dir, "blender.exe"));
            candidates.Add(Path.Combine(dir, "blender"));
        }
        return candidates.FirstOrDefault(File.Exists);
    }

    static Version VersionOf(string dir)
    {
        var m = Regex.Match(Path.GetFileName(dir), @"(\d+)\.(\d+)");
        return m.Success ? new Version(int.Parse(m.Groups[1].Value), int.Parse(m.Groups[2].Value)) : new Version(0, 0);
    }

    // ------------------------------------------------------------------ menu
    [MenuItem("Tools/Kit/Build Kit Script...")]
    static void BuildFromFile()
    {
        string p = EditorUtility.OpenFilePanel("Kit script", Directory.Exists(ScriptsDir) ? ScriptsDir : "", "py");
        if (string.IsNullOrEmpty(p)) return;
        if (!IsKitScript(p)) { EditorUtility.DisplayDialog("Kit Bridge", "That file is not a stylized-blender-assets kit script.", "OK"); return; }
        Offer(p);
    }

    [MenuItem("Tools/Kit/Rebuild Last Kit")]
    static void RebuildLast()
    {
        string p = EditorPrefs.GetString(PrefLast, "");
        if (File.Exists(p)) Offer(p);
        else EditorUtility.DisplayDialog("Kit Bridge", "No kit has been built yet.", "OK");
    }

    [MenuItem("Tools/Kit/Bridge Settings...")]
    static void Settings() => KitBridgeSettings.Open();
}

public class KitBridgeSettings : EditorWindow
{
    public static void Open() => GetWindow<KitBridgeSettings>("Kit Bridge");

    void OnGUI()
    {
        EditorGUILayout.LabelField("Blender", EditorStyles.boldLabel);
        string cur = EditorPrefs.GetString("KitBridge.BlenderPath", "");
        string found = KitBridge.FindBlender() ?? "(not found)";
        EditorGUILayout.LabelField("Using", string.IsNullOrEmpty(cur) ? found + "  (auto)" : cur);
        if (GUILayout.Button("Choose Blender executable..."))
        {
            string p = EditorUtility.OpenFilePanel("Locate Blender", "", "");
            if (!string.IsNullOrEmpty(p)) EditorPrefs.SetString("KitBridge.BlenderPath", p);
        }
        if (GUILayout.Button("Use auto-detect")) EditorPrefs.DeleteKey("KitBridge.BlenderPath");

        EditorGUILayout.Space();
        EditorGUILayout.LabelField("Kit scripts", EditorStyles.boldLabel);
        EditorGUILayout.LabelField("Kept in", "Assets/KitScripts");
        KitBridge.WatchDownloads = EditorGUILayout.Toggle("Watch Downloads folder", KitBridge.WatchDownloads);
        EditorGUILayout.LabelField("Downloads", KitBridge.DownloadsDir);
        EditorGUILayout.HelpBox("Optional, for kits made in Claude chat: a kit script downloaded there opens a " +
                                "Build / Ignore dialog. Not needed when Claude Code builds the kits. " +
                                "Nothing runs without your click.", MessageType.Info);
    }
}
